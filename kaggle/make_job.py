"""Write a Kaggle notebook folder that runs moon2024 commands at the current pushed commit.

  python kaggle/make_job.py SLUG [--source KERNEL ...] [--gpu] -- "run_ensembles search --dataset aep ..." ...

Each quoted argument after -- is one command, run as `python -m moon2024.<command>`.
The folder is written to kaggle/jobs/SLUG; push it with `kaggle kernels push -p kaggle/jobs/SLUG`.
"""

import argparse
import json
import subprocess
from pathlib import Path

USER = "cafein"
REPO = "https://github.com/cafeina13/moon2024-replication"
HERE = Path(__file__).resolve().parent

TEMPLATE = '''"""Kaggle job {slug}: generated by kaggle/make_job.py, do not edit."""

import os
import subprocess
import sys

COMMIT = "{commit}"
COMMANDS = {commands!r}
SRC = "/kaggle/tmp/moon2024-replication"

subprocess.run(["git", "clone", "-q", "{repo}", SRC], check=True)
subprocess.run(["git", "checkout", "-q", COMMIT], cwd=SRC, check=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", "-e", SRC], check=True)
env = {{**os.environ, "MOON_DATA_DIR": "/kaggle/input"}}
for command in COMMANDS:
    print("$ moon2024." + command, flush=True)
    subprocess.run([sys.executable, "-m", "moon2024." + command.split()[0], *command.split()[1:]], env=env, check=True)
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("slug")
    parser.add_argument("--source", action="append", default=[], help="extra kernel whose output is an input")
    parser.add_argument("--gpu", action="store_true")
    parser.add_argument("commands", nargs="+")
    args = parser.parse_args()

    commit = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    pushed = subprocess.run(["git", "branch", "-r", "--contains", commit], capture_output=True, text=True).stdout
    if not pushed.strip():
        raise SystemExit(f"commit {commit[:7]} is not pushed; Kaggle could not check it out")

    folder = HERE / "jobs" / args.slug
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "job.py").write_text(
        TEMPLATE.format(slug=args.slug, commit=commit, commands=args.commands, repo=REPO), encoding="utf-8"
    )
    metadata = {
        "id": f"{USER}/{args.slug}",
        "title": args.slug,
        "code_file": "job.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": args.gpu,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [f"{USER}/moon2024-get-data", *(f"{USER}/{s}" for s in args.source)],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"{folder} at {commit[:7]}")


if __name__ == "__main__":
    main()
